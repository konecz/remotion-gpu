// The videos and paths of the benchmark. Each path knows how to build the render command for each video, or says
// why it does not apply; run.mjs only shuffles the order, measures and records.
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { cpuArgs, gpuChromeArgs, nvencArgs, remotionCommand } from "../src/remotion-gpu.mjs";

export const HERE = dirname(fileURLToPath(import.meta.url));
export const CONFIG = join(HERE, "remotion.config.ts");

export const RESOLUTIONS = { "1080p": [1920, 1080], "4k": [3840, 2160] };

/**
 * Synthetic videos (bench/src). B and C use synthetic footage (bench/public/footage, generated by run.mjs).
 * An external project can be added with run.mjs --external (video "X").
 */
export const VIDEOS = [
  { id: "A", comp: "A-Typography", hasVideo: false, resolutions: ["1080p"] },
  { id: "B", comp: "B-Presenter", hasVideo: true, resolutions: ["1080p", "4k"] },
  { id: "C", comp: "C-Multivideo", hasVideo: true, resolutions: ["1080p"] },
  { id: "D", comp: "D-Effects", hasVideo: false, resolutions: ["1080p"] },
  { id: "E", comp: "E-Slide", hasVideo: false, resolutions: ["1080p"] },
];

/**
 * An external Remotion project as video "X": rendered in its own folder with its own Remotion (npx), frames
 * [start, start + seconds*fps). P0 and P1 apply as-is (P1 assumes the project already uses <Video> from
 * @remotion/media); P2/P3 only with `layersCmd`, a shell command with {output} {from} {to} {work} placeholders that
 * renders that range by layers (RGPU_DEDUP=0 or 1 is set for P2/P3).
 */
export const externalVideo = ({ dir, entry = "src/index.ts", comp, start = 0, fps = 30, layersCmd = null }) => ({
  id: "X", comp, hasVideo: true, resolutions: ["native"], external: { dir, entry, start, fps, layersCmd },
});

export class NotApplicable extends Error {}

/**
 * Render devices (`--device`):
 *   nvidia  the NVIDIA GPU (default; --gpu picks the CUDA index);
 *   cpu     no GPU: CUDA hidden and Vulkan limited to lavapipe (software) when installed; P1 becomes <Video> +
 *           libx264 with software GL, P2/P3 do not apply (they need Vulkan Video and NVENC).
 * Other vendors are not implemented: Remotion 4 only uses NVENC as a hardware encoder on Linux, and P2 would need
 * VA-API (h264_vaapi) or another compositing path.
 */
const LAVAPIPE = "/usr/share/vulkan/icd.d/lvp_icd.json";
export const deviceEnv = (device, gpu) => {
  if (device === "cpu") return { CUDA_VISIBLE_DEVICES: "", ...(existsSync(LAVAPIPE) ? { VK_ICD_FILENAMES: LAVAPIPE, VK_DRIVER_FILES: LAVAPIPE } : {}) };
  if (device === "nvidia") return gpu != null ? { CUDA_VISIBLE_DEVICES: String(gpu) } : {};
  throw new Error(`unknown device "${device}" (nvidia, cpu)`);
};
const nvidiaOnly = (device, what) => {
  if (device !== "nvidia") throw new NotApplicable(`${what}: needs an NVIDIA GPU (device "${device}")`);
};

const props = (res, seconds, video) => {
  const [width, height] = RESOLUTIONS[res];
  return `--props=${JSON.stringify({ width, height, seconds, video })}`;
};
const range = (x, seconds) => {
  const from = x.start;
  return [from, from + Math.round(seconds * x.fps) - 1];
};

/** Synthetic render: our Remotion CLI on the prebuilt bundle. */
const synthetic = (bundle, comp, output, ...args) => {
  const { cmd, args: pre } = remotionCommand({ cwd: HERE });
  return { cmd, args: [...pre, "render", bundle, comp, output, `--config=${CONFIG}`, ...args, "--log=error"], cwd: HERE };
};
/** External render: the project's own Remotion, in its folder. */
const externalArgs = (v, output, seconds, ...args) => {
  const [from, to] = range(v.external, seconds);
  return { cmd: "npx", args: ["remotion", "render", v.external.entry, v.comp, output, `--frames=${from}-${to}`, ...args, "--log=error"], cwd: v.external.dir };
};

/** P2 and P3: the layered render, with or without skipping repeated frames. */
const layers = (dedup) => ({ v, res, seconds, bundle, output, work, device, vulkanDevice }) => {
  nvidiaOnly(device, "layers (Vulkan Video, libplacebo and NVENC)");
  if (v.id === "C") throw new NotApplicable("the layered render puts one take per segment; C shows two to four takes at once (grid and PiP)");
  if (v.external) {
    if (!v.external.layersCmd) throw new NotApplicable("no --external-layers command for this project");
    const [from, to] = range(v.external, seconds);
    const cmd = v.external.layersCmd.replaceAll("{output}", output).replaceAll("{from}", String(from)).replaceAll("{to}", String(to)).replaceAll("{work}", work);
    return { cmd: "sh", args: ["-c", cmd], cwd: v.external.dir, env: { RGPU_DEDUP: dedup ? "1" : "0" } };
  }
  const [width, height] = RESOLUTIONS[res];
  return {
    cmd: process.execPath,
    args: [
      join(HERE, "layers.mjs"), v.comp, "--bundle", bundle, "--width", String(width), "--height", String(height), "--seconds", String(seconds),
      "--work", work, "--output", output, "--steps", join(work, "steps.json"), ...(dedup ? ["--dedup"] : []),
      ...(vulkanDevice != null ? ["--vulkan-device", String(vulkanDevice)] : []),
    ],
    cwd: HERE,
    steps: join(work, "steps.json"),
  };
};

/**
 * Paths. `command(ctx)` returns { cmd, args, cwd, env?, steps? } or throws NotApplicable with the reason.
 * ctx: { v, res, seconds, bundle, output, work, device, vulkanDevice }.
 */
export const PATHS = [
  {
    id: "P0",
    name: "Remotion defaults",
    description: "<OffthreadVideo>, JPEG sequence (quality 80) and Remotion's libx264 CRF 18; no --gl (Chrome decides), default concurrency",
    command: ({ v, res, seconds, bundle, output }) =>
      v.external ? externalArgs(v, output, seconds) : synthetic(bundle, v.comp, output, props(res, seconds, "offthread")),
  },
  {
    id: "P1",
    name: "Remotion on the GPU",
    description: "<Video> from @remotion/media (WebCodecs), Chrome with Vulkan, MP4 straight from h264_nvenc at 12 Mb/s, JPEG 95 (on device cpu: software GL and libx264)",
    command: ({ v, res, seconds, bundle, output, device }) => {
      const flags = device === "cpu" ? cpuArgs() : (nvidiaOnly(device, "P1"), [...gpuChromeArgs(), ...nvencArgs()]);
      return v.external ? externalArgs(v, output, seconds, ...flags) : synthetic(bundle, v.comp, output, props(res, seconds, "media"), ...flags);
    },
  },
  {
    id: "P2",
    name: "Layers",
    description: "Remotion for graphics only (PNG with alpha, Vulkan) + ffmpeg on the GPU: Vulkan Video (NVDEC), libplacebo, h264_nvenc CQ 19",
    command: (ctx) => layers(false)(ctx),
  },
  {
    id: "P3",
    name: "Layers + skip repeated frames",
    description: "P2 with the graphics capture skipping frames whose page state (SHA-256 of DOM and CSS) was already captured",
    command: (ctx) => layers(true)(ctx),
  },
];

/**
 * Quality reference of a video: the P0 path with PNG capture and ProRes 4444 XQ, nearly lossless. Remotion refuses
 * CRF 0 for H.264, and an image sequence (--sequence) picks the take's frame differently from a video render, so it
 * does not serve as reference.
 */
export const referenceCommand = ({ v, res, seconds, bundle, output }) => {
  const always = ["--image-format=png", "--codec=prores", "--prores-profile=4444-xq"];
  return v.external ? externalArgs(v, output, seconds, ...always) : synthetic(bundle, v.comp, output, props(res, seconds, "offthread"), ...always);
};
